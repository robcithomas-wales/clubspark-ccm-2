function portalEnv(name, spec, root, portTable) {
  const lines = []
  lines.push(GENERATED_MARKER)
  lines.push('# Edit the root .env and re-run `npm run setup:env`.')
  lines.push('')
  if (spec.publicSupabase) {
    lines.push(`NEXT_PUBLIC_SUPABASE_URL=${root.SUPABASE_URL}`)
    if (!root.SUPABASE_ANON_KEY) {
      throw new Error(`${name} needs SUPABASE_ANON_KEY but the root .env does not define it`)
    }
    lines.push(`NEXT_PUBLIC_SUPABASE_ANON_KEY=${root.SUPABASE_ANON_KEY}`)
  }
  if (spec.internalSecret) {
    lines.push('')
    lines.push('# Must match the services byte-for-byte; the guard is fail-closed.')
    lines.push(`INTERNAL_SECRET=${root.INTERNAL_SECRET}`)
  }
  if (spec.anthropic && root.ANTHROPIC_API_KEY) {
    lines.push(`ANTHROPIC_API_KEY=${root.ANTHROPIC_API_KEY}`)
  }
  if (spec.baseDomain && root.PUBLIC_BASE_DOMAIN) {
    lines.push(`NEXT_PUBLIC_BASE_DOMAIN=${root.PUBLIC_BASE_DOMAIN}`)
  }
  lines.push('')
  lines.push('# Service URLs — derived from the port table in scripts/run-all.sh.')
  for (const [key, peer] of Object.entries(spec.peers)) {
    const port = portTable[peer]
    if (!port) throw new Error(`${name}: no port for peer '${peer}'`)
    lines.push(`${key}=http://127.0.0.1:${port}`)
  }
  lines.push('')
  return lines.join('\n')
}

// Values a single service must differ on live in services/<name>/.env.override
// (git-ignored). They are merged in here, at generation time, so nothing in the
// 15 services' startup code has to know about a second file.
function readOverride(dir) {
  const file = path.join(dir, '.env.override')
  if (!fs.existsSync(file)) return null
  const parsed = parseEnv(fs.readFileSync(file, 'utf8'))
  const blocked = Object.keys(parsed).filter((k) => OVERRIDE_DENYLIST.has(k))
  if (blocked.length) {
    throw new Error(`.env.override may not set ${blocked.join(', ')} (security-relevant)`)
  }
  return Object.keys(parsed).length ? parsed : null
}

function applyOverride(body, override) {
  if (!override) return body
  const lines = body.split('\n')
  const remaining = { ...override }
  const out = lines.map((line) => {
    const m = line.match(/^([A-Z0-9_]+)=/)
    if (m && Object.prototype.hasOwnProperty.call(remaining, m[1])) {
      const v = remaining[m[1]]
      delete remaining[m[1]]
      return `${m[1]}=${v}`
    }
    return line
  })
  const added = Object.entries(remaining)
  if (added.length) {
    out.push('# Added by .env.override')
    for (const [k, v] of added) out.push(`${k}=${v}`)
    out.push('')
  }
  return out.join('\n')
}

function serviceEnv(name, port, root, portTable) {
  const lines = []
  lines.push(GENERATED_MARKER)
  lines.push('# Edit the root .env and re-run `npm run setup:env`.')
  lines.push('# Service-specific values that must differ: put them in .env.override')
  lines.push('# (same directory, git-ignored) — setup:env merges them in here.')
  lines.push('')
  lines.push(`PORT=${port}`)
  lines.push(`NODE_ENV=${root.NODE_ENV || 'development'}`)
  lines.push('')
  lines.push('# Database. Pooler flags (pgbouncer, connection_limit, pool_timeout) are')
  lines.push('# applied once, by PrismaService, from DB_CONNECTION_LIMIT below.')
  lines.push(`DATABASE_URL=${runtimeUrl(root.DATABASE_URL)}`)
  lines.push(`DB_CONNECTION_LIMIT=${root.DB_CONNECTION_LIMIT || '1'}`)
  if (root.DATABASE_READ_URL) lines.push(`DATABASE_READ_URL=${root.DATABASE_READ_URL}`)
  lines.push('')
  lines.push('# Auth / platform')
  lines.push(`SUPABASE_URL=${root.SUPABASE_URL}`)
  if (root.SUPABASE_JWT_SECRET) lines.push(`SUPABASE_JWT_SECRET=${root.SUPABASE_JWT_SECRET}`)
  if (SERVICE_ROLE_KEY_ALLOWLIST.has(name)) {
    if (!root.SUPABASE_SERVICE_ROLE_KEY) {
      throw new Error(
        `${name}-service needs SUPABASE_SERVICE_ROLE_KEY but the root .env does not define it`,
      )
    }
    lines.push(`SUPABASE_SERVICE_ROLE_KEY=${root.SUPABASE_SERVICE_ROLE_KEY}`)
  }
  lines.push(`INTERNAL_SECRET=${root.INTERNAL_SECRET}`)
  if (root.CLUBSPARK_REGION) lines.push(`CLUBSPARK_REGION=${root.CLUBSPARK_REGION}`)
  if (root.ANTHROPIC_API_KEY) lines.push(`ANTHROPIC_API_KEY=${root.ANTHROPIC_API_KEY}`)
  const extras = SERVICE_EXTRA_KEYS[name] || []
  if (extras.length) {
    lines.push('')
    lines.push(`# Keys only ${name}-service uses. Set them in the root .env.`)
    for (const { key } of extras) if (root[key]) lines.push(`${key}=${root[key]}`)
  }
  lines.push('')
  lines.push('# Peer services — derived from the port table in scripts/run-all.sh.')
  for (const [peer, peerPort] of Object.entries(portTable)) {
    if (peer === name) continue
    lines.push(`${peer.toUpperCase()}_SERVICE_URL=http://127.0.0.1:${peerPort}`)
  }
  for (const [alias, target] of Object.entries(URL_ALIASES)) {
    if (target === name) continue
    lines.push(`${alias}=http://127.0.0.1:${portTable[target]}`)
  }
  lines.push('')
  return lines.join('\n')
}

// ── Main ─────────────────────────────────────────────────────────────────────
const portTable = readPortTable()
const root = loadRoot()

const EXTRA_KEY_NAMES = Object.values(SERVICE_EXTRA_KEYS)
  .flat()
  .map((e) => e.key)
const unknown = Object.keys(root).filter(
  (k) => ![...REQUIRED_ROOT_KEYS, ...OPTIONAL_ROOT_KEYS, ...EXTRA_KEY_NAMES].includes(k),
)

const rows = []
let wrote = 0
let problems = 0

for (const [name, port] of Object.entries(portTable)) {
  const dir = path.join(ROOT, 'services', `${name}-service`)
  if (!fs.existsSync(dir)) {
    rows.push([name, 'no service directory', 'SKIP'])
    continue
  }
  const file = path.join(dir, '.env')
  let content
  let override
  try {
    override = readOverride(dir)
    content = applyOverride(serviceEnv(name, port, root, portTable), override)
  } catch (e) {
    rows.push([name, e.message, 'FAIL'])
    problems++
    continue
  }
  const note = override ? ` +override(${Object.keys(override).length})` : ''

  const exists = fs.existsSync(file)
  const current = exists ? fs.readFileSync(file, 'utf8') : ''
  const isGenerated = current.startsWith(GENERATED_MARKER)

  if (CHECK) {
    // Mode is checked, not assumed: writeFileSync's `mode` only applies when it
    // creates the file, so a pre-existing 0644 stays 0644 on a rewrite.
    const loose = exists && (fs.statSync(file).mode & 0o077) !== 0
    if (!exists) {
      rows.push([name, 'missing .env', 'FAIL'])
      problems++
    } else if (loose) {
      rows.push([name, 'world/group-readable — re-run setup:env', 'FAIL'])
      problems++
    } else if (!isGenerated) {
      rows.push([name, 'hand-edited (not generated)', 'WARN'])
    } else if (current !== content) {
      rows.push([name, 'stale — re-run setup:env', 'FAIL'])
      problems++
    } else {
      // Flag production-required secrets that fall back to a committed dev
      // default inside the service — unset is silently insecure, not a failure.
      const weak = (SERVICE_EXTRA_KEYS[name] || [])
        .filter((e) => e.productionRequired && !root[e.key])
        .map((e) => e.key)
      if (weak.length) rows.push([name, `using dev defaults for ${weak.join(', ')}`, 'WARN'])
      else rows.push([name, `port ${port}${note}`, 'ok'])
    }
    continue
  }

  if (exists && !isGenerated && !FORCE) {
    rows.push([name, 'hand-edited — refusing to clobber (use --force)', 'SKIP'])
    problems++
    continue
  }

  // Always chmod, never rely on writeFileSync's mode: it is honoured only on
  // create, so a rewrite would silently leave the previous (often 0644) mode on
  // a file holding the database password, INTERNAL_SECRET and possibly the
  // RLS-bypassing service-role key.
  const modeWasLoose = exists && (fs.statSync(file).mode & 0o077) !== 0
  if (current === content && !modeWasLoose) {
    rows.push([name, `port ${port}${note}`, 'unchanged'])
    continue
  }
  fs.writeFileSync(file, content)
  fs.chmodSync(file, 0o600)
  wrote++
  rows.push([name, `port ${port}${note}`, exists ? 'rewritten' : 'created'])
}

// ── Portals (generation) ──────────────────────────────────────────────────
for (const [name, spec] of Object.entries(PORTALS)) {
  const dir = path.join(ROOT, name)
  if (!fs.existsSync(dir)) {
    rows.push([name, 'no directory', 'SKIP'])
    continue
  }
  const file = path.join(dir, spec.file)
  let content
  try {
    content = portalEnv(name, spec, root, portTable)
  } catch (e) {
    rows.push([name, e.message, 'FAIL'])
    problems++
    continue
  }
  const exists = fs.existsSync(file)
  const current = exists ? fs.readFileSync(file, 'utf8') : ''
  const isGenerated = current.startsWith(GENERATED_MARKER)
  const loose = exists && (fs.statSync(file).mode & 0o077) !== 0

  if (CHECK) {
    if (!exists) {
      rows.push([name, 'missing ' + spec.file, 'FAIL'])
      problems++
    } else if (loose) {
      rows.push([name, 'world/group-readable — re-run setup:env', 'FAIL'])
      problems++
    } else if (!isGenerated) {
      rows.push([name, 'hand-edited, not generated', 'WARN'])
    } else if (current !== content) {
      rows.push([name, 'stale — re-run setup:env', 'FAIL'])
      problems++
    } else {
      rows.push([name, spec.file, 'ok'])
    }
    continue
  }

  if (exists && !isGenerated && !FORCE) {
    rows.push([name, 'hand-edited — refusing to clobber, use --force', 'SKIP'])
    problems++
    continue
  }
  if (current === content && !loose) {
    rows.push([name, spec.file, 'unchanged'])
    continue
  }
  fs.writeFileSync(file, content)
  fs.chmodSync(file, 0o600)
  wrote++
  rows.push([name, spec.file, exists ? 'rewritten' : 'created'])
}

const w = Math.max(...rows.map((r) => r[0].length))
for (const [a, b, c] of rows) console.log(`  ${a.padEnd(w)}  ${c.padEnd(10)} ${b}`)

if (unknown.length) {
  console.log(`\n  note: root .env has keys this script does not propagate: ${unknown.join(', ')}`)
}

if (CHECK) {
  console.log(
    `\n  ${problems === 0 ? 'env OK' : `${problems} problem(s)`} across ${rows.length} services`,
  )
  process.exit(problems === 0 ? 0 : 1)
}
console.log(`\n  wrote ${wrote} of ${rows.length} service env files (mode 0600)`)
console.log('  DIRECT_DATABASE_URL is intentionally not set — use `npm run migrate:all`.')
// Exit non-zero on any FAIL/SKIP in generate mode too. Previously only --check
// consulted `problems`, so `npm run setup:env && npm run start:services` would
// carry on after leaving a service with no .env, or a drifted hand-edited one.
if (problems > 0) {
  console.error(
    `\n  ${problems} service(s) not generated — see above. Nothing downstream should run.`,
  )
  process.exit(1)
}
