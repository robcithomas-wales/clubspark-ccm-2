#!/usr/bin/env node
//
// setup-env.mjs — generate every services/<name>/.env from ONE root .env.
//
// Why this exists: the platform has 15 services that all talk to the same
// database and the same Supabase project. Before this script each engineer
// hand-maintained 15 copies of the same connection string, and they drifted:
// `booking-service` had PORT=4017 while the canonical port is 4005, only
// `template-service` carried the pgbouncer flags the transaction pooler needs,
// and DIRECT_DATABASE_URL was referenced by every schema.prisma but defined
// nowhere. One file to edit, one command to run, no drift.
//
// Usage:
//   node scripts/setup-env.mjs            # generate (refuses to clobber edits)
//   node scripts/setup-env.mjs --force    # overwrite generated files
//   node scripts/setup-env.mjs --check    # verify only, non-zero on problems
//
// Secrets are never printed — output reports key names and shapes only.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const args = new Set(process.argv.slice(2))
const FORCE = args.has('--force')
const CHECK = args.has('--check')

const GENERATED_MARKER = '# GENERATED by `npm run setup:env` — DO NOT EDIT.'

// ── Canonical service registry ───────────────────────────────────────────────
// Ports come from run-all.sh so there is exactly one place they are declared.
function readPortTable() {
  const sh = fs.readFileSync(path.join(ROOT, 'scripts', 'run-all.sh'), 'utf8')
  const m = sh.match(/^SERVICES="([^"]+)"/m)
  if (!m) throw new Error('Could not find SERVICES=... in scripts/run-all.sh')
  const table = {}
  for (const pair of m[1].trim().split(/\s+/)) {
    const [name, port] = pair.split(':')
    table[name] = Number(port)
  }
  return table
}

// Services granted the Supabase service-role key. It bypasses row-level
// security, so this is an allowlist, not a default — do not add a service
// without a code reference to justify it.
//
// venue-service is the only consumer: venues.controller.ts and
// organisations.controller.ts. comms-service was on this list historically but
// has no reference to the key anywhere in src/, so it no longer receives it.
const SERVICE_ROLE_KEY_ALLOWLIST = new Set(['venue'])

// Keys only one or two services consume. They are propagated from the root .env
// when set, listed in that service's .env.example, and reported by --check when
// missing so they cannot disappear from the record again.
//
// `productionRequired` keys fall back to a committed dev default inside the
// service (see services/integration-service/src/config/configuration.ts) — which
// means an unset value is silently insecure rather than a startup failure, so
// --check flags it.
const SERVICE_EXTRA_KEYS = {
  integration: [
    { key: 'API_KEY_HASH_SECRET', productionRequired: true },
    { key: 'TOKEN_ENCRYPTION_KEY', productionRequired: true },
    { key: 'OAUTH_STATE_SECRET', productionRequired: true },
  ],
  comms: [
    { key: 'RESEND_API_KEY' },
    { key: 'RESEND_FROM_ADDRESS' },
    { key: 'AZURE_COMMUNICATION_CONNECTION_STRING' },
    { key: 'AZURE_COMMUNICATION_SENDER_ADDRESS' },
    { key: 'AZURE_COMMUNICATION_PHONE_NUMBER' },
    { key: 'AZURE_SERVICE_BUS_CONNECTION_STRING' },
    { key: 'AZURE_SERVICE_BUS_TOPICS' },
  ],
  template: [{ key: 'REDIS_URL' }],
}

// Non-standard aliases some services use for a peer's URL.
const URL_ALIASES = { CUSTOMER_SERVICE_URL: 'people' }

// ── Root .env ────────────────────────────────────────────────────────────────
const REQUIRED_ROOT_KEYS = ['DATABASE_URL', 'SUPABASE_URL', 'INTERNAL_SECRET']
const OPTIONAL_ROOT_KEYS = [
  'SUPABASE_SERVICE_ROLE_KEY',
  'SUPABASE_JWT_SECRET',
  'CLUBSPARK_REGION',
  'REDIS_URL',
  'DATABASE_READ_URL',
  'ANTHROPIC_API_KEY',
  'DB_CONNECTION_LIMIT',
  'SUPABASE_ANON_KEY',
  'PUBLIC_BASE_DOMAIN',
  'NODE_ENV',
]

function parseEnv(text) {
  const out = {}
  for (const line of text.split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/)
    if (!m) continue
    let value = m[2].trim()
    const quoted = /^(["'])(.*)\1$/.exec(value)
    if (quoted) {
      value = quoted[2]
    } else {
      // Strip an unquoted trailing comment. Without this,
      // `DB_CONNECTION_LIMIT=5 # note` yields the value "5 # note", which then
      // lands verbatim in a connection string.
      value = value.replace(/\s+#.*$/, '').trim()
    }
    out[m[1]] = value
  }
  return out
}

function loadRoot() {
  const file = path.join(ROOT, '.env')
  if (!fs.existsSync(file)) {
    console.error('\n  No root .env found.\n')
    console.error('  Copy the template and fill in the real values:')
    console.error('      cp .env.example .env\n')
    console.error('  It needs: ' + REQUIRED_ROOT_KEYS.join(', ') + '\n')
    process.exit(1)
  }
  const env = parseEnv(fs.readFileSync(file, 'utf8'))
  const missing = REQUIRED_ROOT_KEYS.filter((k) => !env[k])
  if (missing.length) {
    console.error(`\n  Root .env is missing: ${missing.join(', ')}\n`)
    process.exit(1)
  }
  // NODE_ENV=test would disable InternalSecretGuard on every service (it returns
  // true outright in that mode), leaving the internal cross-tenant write routes
  // unauthenticated. Never let it reach a generated file.
  if (env.NODE_ENV && !['development', 'production'].includes(env.NODE_ENV)) {
    console.error(
      `\n  Root .env sets NODE_ENV=${env.NODE_ENV}. Only 'development' or 'production' are allowed here.` +
        `\n  NODE_ENV=test disables InternalSecretGuard, which is the only authenticator on the` +
        `\n  internal reassign-customer and events/inbound routes. The test harnesses set it themselves.\n`,
    )
    process.exit(1)
  }
  // The root file holds the database password and INTERNAL_SECRET; `cp` from the
  // tracked example inherits 0644.
  if ((fs.statSync(file).mode & 0o077) !== 0) {
    fs.chmodSync(file, 0o600)
    console.log('  note: tightened root .env to 0600')
  }
  return env
}

// ── Connection strings ───────────────────────────────────────────────────────
// The generator does NOT append pgbouncer/connection_limit flags.
//
// PrismaService already appends `pgbouncer=true&connection_limit=N&pool_timeout=10`
// in all 15 services, and every test/helpers/db.ts appends its own. A third set
// here produced a doubled query string, e.g.
//   ?pgbouncer=true&connection_limit=5?pgbouncer=true&connection_limit=1&pool_timeout=10
// which Prisma 5.22 accepts while the LAST duplicate wins — so anything written
// here was silently ignored, and a future Prisma version would reject it outright.
//
// One owner: PrismaService. It reads DB_CONNECTION_LIMIT (default 1), which this
// script propagates, so the knob lives in the root .env and applies exactly once.
//
// The credential is passed through untouched. Parsing it with `new URL()` and
// re-serialising corrupts any password containing `#` or `?`, splicing query
// params into the middle of the credential.
function runtimeUrl(base) {
  const lastAt = base.lastIndexOf('@')
  const credentials = lastAt === -1 ? '' : base.slice(0, lastAt)
  if (/[?#]/.test(credentials)) {
    throw new Error(
      'DATABASE_URL credentials contain a raw ? or # — percent-encode them (%3F / %23)',
    )
  }
  return base
}

// DIRECT_DATABASE_URL is deliberately NOT generated.
//
// Nothing at runtime reads it — Prisma Client connects via `url`; `directUrl` is
// used only by the Prisma CLI. Both sanctioned migration paths
// (scripts/migrate-all.sh, scripts/check-migration-drift.sh) derive it
// themselves, per service, including the ?schema= pin. Leaving it undefined means
// an ad-hoc `npx prisma migrate deploy` inside a service directory fails fast
// with P1012 instead of running — and that is the desired outcome, because the
// ad-hoc path skips the shared bootstrap SQL and the multi-pass ordering that
// exists for cross-schema function dependencies. Use `npm run migrate:all`.

// Keys an override may never set. `.env.override` is the lowest-trust input in
// the system — git-ignored, per-machine, unreviewed — so it must not be able to
// weaken a security control:
//
//   NODE_ENV                  — InternalSecretGuard returns true outright when
//                               NODE_ENV==='test', and it reads process.env per
//                               request. That guard is the SOLE authenticator on
//                               the internal reassign-customer and events/inbound
//                               routes, which take the tenant from a header.
//   INTERNAL_SECRET           — the service-to-service authenticator.
//   SUPABASE_SERVICE_ROLE_KEY — bypasses row-level security; allowlisted above.
//   DIRECT_DATABASE_URL       — deliberately unset so ad-hoc prisma migrate
//                               fails fast rather than skipping migrate-all.sh.
const OVERRIDE_DENYLIST = new Set([
  'NODE_ENV',
  'INTERNAL_SECRET',
  'SUPABASE_SERVICE_ROLE_KEY',
  'DIRECT_DATABASE_URL',
])

// ── Portals ──────────────────────────────────────────────────────────────────
// The three Next.js apps are generated too. They were previously outside this
// script, which is how internal-portal's INTERNAL_SECRET came to drift from the
// services' — and admin-service's guard is fail-closed, so the symptom was every
